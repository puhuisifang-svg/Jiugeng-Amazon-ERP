CREATE TABLE customer_invoice (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    customer_product_id VARCHAR(36) NOT NULL,
    customer_id VARCHAR(36) NOT NULL,
    customer_name VARCHAR(128) NOT NULL,
    invoice_title VARCHAR(200) NOT NULL,
    tax_number VARCHAR(64) NOT NULL DEFAULT '',
    registered_address VARCHAR(500) NOT NULL DEFAULT '',
    registered_phone VARCHAR(32) NOT NULL DEFAULT '',
    bank_name VARCHAR(200) NOT NULL DEFAULT '',
    bank_account VARCHAR(64) NOT NULL DEFAULT '',
    item_name VARCHAR(200) NOT NULL,
    specification VARCHAR(200) NOT NULL DEFAULT '',
    unit VARCHAR(16) NOT NULL,
    quantity DECIMAL(12,3) NOT NULL,
    net_unit_price DECIMAL(14,6) NOT NULL,
    tax_rate DECIMAL(5,2) NOT NULL DEFAULT 1,
    net_amount DECIMAL(20,2) NOT NULL,
    tax_amount DECIMAL(20,2) NOT NULL,
    total_amount DECIMAL(20,2) NOT NULL,
    shipped BOOLEAN NOT NULL DEFAULT FALSE,
    invoiced BOOLEAN NOT NULL DEFAULT FALSE,
    logistics VARCHAR(1000) NOT NULL DEFAULT '',
    version BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(36) NOT NULL,
    updated_by VARCHAR(36) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_invoice_customer FOREIGN KEY (customer_id) REFERENCES customer(id),
    CONSTRAINT fk_invoice_customer_product FOREIGN KEY (customer_product_id) REFERENCES customer_product(id),
    CONSTRAINT ck_invoice_quantity CHECK (quantity > 0),
    CONSTRAINT ck_invoice_price CHECK (net_unit_price >= 0),
    CONSTRAINT ck_invoice_rate CHECK (tax_rate >= 0 AND tax_rate <= 100)
);
CREATE INDEX idx_invoice_status ON customer_invoice(invoiced, shipped, updated_at);
CREATE INDEX idx_invoice_customer ON customer_invoice(customer_id, updated_at);
