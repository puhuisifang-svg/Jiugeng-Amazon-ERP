CREATE TABLE iam_role (
 id VARCHAR(64) PRIMARY KEY, name VARCHAR(50) NOT NULL, description VARCHAR(200) NOT NULL DEFAULT '',
 kind VARCHAR(16) NOT NULL, status VARCHAR(16) NOT NULL, version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at TIMESTAMP NULL
);
CREATE TABLE iam_role_permission (role_id VARCHAR(64) NOT NULL, permission_code VARCHAR(100) NOT NULL,
 PRIMARY KEY(role_id,permission_code), FOREIGN KEY(role_id) REFERENCES iam_role(id));
CREATE TABLE iam_user_role (user_id VARCHAR(64) NOT NULL, role_id VARCHAR(64) NOT NULL,
 PRIMARY KEY(user_id,role_id), FOREIGN KEY(user_id) REFERENCES iam_user(id) ON DELETE CASCADE,
 FOREIGN KEY(role_id) REFERENCES iam_role(id));
CREATE TABLE iam_authorization_lock (id INT PRIMARY KEY);
