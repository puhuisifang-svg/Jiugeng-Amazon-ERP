import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ documents: vi.fn(), uploadDocument: vi.fn(), downloadDocument: vi.fn(), canAccess: vi.fn() }))
vi.mock('@/api/catalog', () => ({ catalogApi: mocks }))
vi.mock('@/state/session', () => ({ session: { canAccess: mocks.canAccess } }))
import SkuDocumentsPanel from './SkuDocumentsPanel.vue'
const document = { id: 'doc1', kind: 'MANUAL', fileName: '说明书.pdf', byteSize: 12, uploadedAt: '2026-10-16T00:00:00Z' }
const render = (kind: 'MANUAL' | 'LABEL' = 'MANUAL') => mount(SkuDocumentsPanel, { props: { productId: 'p1', variantId: 'v1', kind } })
async function upload(wrapper: ReturnType<typeof render>, file: File) {
  const input = wrapper.get('input[type="file"]')
  Object.defineProperty(input.element, 'files', { value: [file], configurable: true })
  await input.trigger('change')
  await flushPromises()
}
describe('SKU documents', () => {
  beforeEach(() => {
    vi.resetAllMocks()
    mocks.canAccess.mockReturnValue(true)
    mocks.documents.mockResolvedValue([])
    mocks.uploadDocument.mockResolvedValue(document)
    mocks.downloadDocument.mockResolvedValue(undefined)
  })
  it('uploads to the selected SKU and kind, then downloads the returned file', async () => {
    const wrapper = render()
    await flushPromises()
    const file = new File(['%PDF-test'], '说明书.pdf', { type: 'application/pdf' })
    await upload(wrapper, file)
    expect(mocks.uploadDocument).toHaveBeenCalledWith('p1', 'v1', 'MANUAL', file)
    expect(wrapper.text()).toContain('上传成功')
    await wrapper.findAll('button').find(button => button.text() === '下载')!.trigger('click')
    await flushPromises()
    expect(mocks.downloadDocument).toHaveBeenCalledWith('p1', 'v1', document)
  })
  it('loads labels separately and hides upload for read-only users', async () => {
    mocks.canAccess.mockReturnValue(false)
    mocks.documents.mockResolvedValue([document])
    const wrapper = render('LABEL')
    await flushPromises()
    expect(mocks.documents).toHaveBeenCalledWith('p1', 'v1', 'LABEL')
    expect(wrapper.find('input[type="file"]').exists()).toBe(false)
    expect(wrapper.text()).toContain('下载')
  })
  it('rejects empty and oversized files before requesting upload', async () => {
    const wrapper = render()
    await flushPromises()
    await upload(wrapper, new File([], 'empty.pdf'))
    expect(wrapper.get('[role="alert"]').text()).toContain('不能为空')
    const file = new File(['x'], 'large.pdf')
    Object.defineProperty(file, 'size', { value: 10 * 1024 * 1024 + 1 })
    await upload(wrapper, file)
    expect(mocks.uploadDocument).not.toHaveBeenCalled()
  })
  it('shows list, upload and download errors and supports retry', async () => {
    mocks.documents.mockRejectedValueOnce(new Error('读取失败'))
    const wrapper = render()
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('读取失败')
    await wrapper.get('button').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('暂无文件')
    mocks.uploadDocument.mockRejectedValueOnce(new Error('格式无效'))
    await upload(wrapper, new File(['bad'], 'bad.pdf'))
    expect(wrapper.get('[role="alert"]').text()).toContain('格式无效')
    await upload(wrapper, new File(['%PDF-ok'], 'valid.pdf'))
    mocks.downloadDocument.mockRejectedValueOnce(new Error('下载失败'))
    await wrapper.findAll('button').find(button => button.text() === '下载')!.trigger('click')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('下载失败')
    expect(wrapper.findAll('button').find(button => button.text() === '下载')!.attributes('disabled')).toBeUndefined()
  })
})
