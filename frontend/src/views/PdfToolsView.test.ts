import { mount, flushPromises } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { PDFDocument } from 'pdf-lib'
import PdfToolsView from './PdfToolsView.vue'
vi.mock('@/components/PdfTextLayer.vue', () => ({ default: { props: ['layer', 'scale'], template: '<span>{{ layer.text }}</span>' } }))
vi.mock('@/components/PdfPagePreview.vue', () => ({ default: { props: ['bytes','page'], template: '<div class="preview-stub"><slot /></div>' } }))
vi.mock('@/utils/labelContentBounds', () => ({ labelContentBounds: vi.fn(async () => undefined) }))
vi.mock('@/directives/singleSelect', () => ({ vSingleSelect: {} }))
const wrappers: ReturnType<typeof mount>[] = []
function setup() { const w = mount(PdfToolsView); wrappers.push(w); return w }
async function selectPdf(w: ReturnType<typeof mount>, name = 'Synthetic.pdf', count = 2) {
  const doc = await PDFDocument.create(); for (let index = 0; index < count; index++) doc.addPage([306,432]).drawText(`Synthetic page ${index + 1}`)
  const bytes = await doc.save()
  const input = w.find('input[type=file]')
  Object.defineProperty(input.element, 'files', { configurable: true, value: [{ name, size:bytes.length, arrayBuffer: async () => bytes.buffer }] })
  await input.trigger('change'); await flushPromises()
}
beforeEach(() => { vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} }) })
afterEach(() => { wrappers.splice(0).forEach(w=>w.unmount()); vi.unstubAllGlobals() })
describe('PDF tools workspace', () => {
  it('keeps four tools together and disables export until a file is selected', () => {
    const w = setup()
    expect(w.findAll('.pdf-tabs button').map(b=>b.text())).toEqual(['拆分PDF','图片转PDF','编辑PDF文件','FBA外箱标转换'])
    expect(w.get('.primary').attributes('disabled')).toBeDefined()
    expect(w.text()).toContain('文件仅在当前浏览器处理')
  })
  it('shows range errors inline instead of starting a broken download', async () => {
    const w = setup(); await selectPdf(w)
    expect(w.text()).toContain('共2页')
    await w.get('input[placeholder="例如：1-3,5,7-9"]').setValue('3-9')
    await w.get('.primary').trigger('click'); await flushPromises()
    expect(w.get('[role=alert]').text()).toContain('页码必须在1～2内')
    expect(w.get('.primary').attributes('disabled')).toBeUndefined()
  })
  it('keeps annotations attached to their page and allows removing a selected annotation', async () => {
    const w = setup()
    await w.findAll('.pdf-tabs button')[2]!.trigger('click')
    await selectPdf(w)
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click')
    expect(w.findAll('.pdf-layer')).toHaveLength(1)
    await w.get('[aria-label="前往第2页"]').trigger('click')
    expect(w.findAll('.pdf-layer')).toHaveLength(1)
    expect(w.findAll('.pdf-document-page')[0]!.find('.pdf-layer').exists()).toBe(true)
    expect(w.findAll('.pdf-document-page')[1]!.find('.pdf-layer').exists()).toBe(false)
    await w.get('[aria-label="前往第1页"]').trigger('click')
    await w.find('.layer-settings button').trigger('click')
    expect(w.findAll('.pdf-layer')).toHaveLength(0)
  })
  it('isolates uploaded PDFs, ranges, previews and current page between tools', async () => {
    const w = setup(); await selectPdf(w, 'Split.pdf')
    await w.get('.pdf-settings select').setValue('ranges')
    await w.get('input[placeholder="例如：1-3,5,7-9"]').setValue('2')
    await w.find('.pdf-pagebar select').setValue('1')
    for (const index of [1,2,3]) {
      await w.findAll('.pdf-tabs button')[index]!.trigger('click')
      expect(w.text()).not.toContain('Split.pdf')
      expect(w.find('.preview-stub').exists()).toBe(false)
      expect(w.get('.primary').attributes('disabled')).toBeDefined()
    }
    await selectPdf(w, 'Label.pdf')
    expect(w.find('.preview-stub').exists()).toBe(true)
    await w.findAll('.pdf-tabs button')[0]!.trigger('click')
    expect(w.text()).toContain('Split.pdf')
    expect(w.text()).not.toContain('Label.pdf')
    expect((w.get('input[placeholder="例如：1-3,5,7-9"]').element as HTMLInputElement).value).toBe('2')
    expect((w.get('.pdf-pagebar select').element as HTMLSelectElement).value).toBe('1')
    await w.findAll('.pdf-tabs button')[3]!.trigger('click')
    expect(w.text()).toContain('Label.pdf')
    expect(w.text()).toContain('转换后')
  })
  it('preserves editor annotations when another tool replaces its own file', async () => {
    const w = setup()
    await w.findAll('.pdf-tabs button')[2]!.trigger('click')
    await selectPdf(w, 'Edit.pdf')
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click')
    await w.get('textarea').setValue('保留的标注')
    await w.findAll('.pdf-tabs button')[0]!.trigger('click')
    await selectPdf(w, 'Other.pdf')
    await w.findAll('.pdf-tabs button')[2]!.trigger('click')
    expect(w.text()).toContain('Edit.pdf')
    expect(w.get('.pdf-layer').text()).toBe('保留的标注')
  })

  it('selects thumbnail pages, clears selection and resets it when replacing the PDF', async () => {
    const w = setup(); await selectPdf(w)
    expect((w.get('.pdf-settings select').element as HTMLSelectElement).value).toBe('merge')
    expect(w.findAll('.pdf-thumbnail')).toHaveLength(2)
    expect(w.get('.primary').text()).toContain('合并所选页面')
    await w.get('[aria-label="选择第1页"]').trigger('click')
    expect(w.get('[aria-label="选择第1页"]').attributes('aria-pressed')).toBe('false')
    expect((w.get('input[placeholder="例如：1-3,5,7-9"]').element as HTMLInputElement).value).toBe('2')
    await w.findAll('button').find(b => b.text() === '清空')!.trigger('click')
    await w.get('.primary').trigger('click'); await flushPromises()
    expect(w.get('[role=alert]').text()).toContain('请输入页码')
    await selectPdf(w, 'Replacement.pdf')
    expect(w.findAll('.pdf-thumbnail.checked')).toHaveLength(2)
  })
  it('keeps all PDF pages in one selection grid beyond the old twelve-page boundary', async () => {
    const w = setup(); await selectPdf(w, 'Long.pdf', 25)
    expect(w.findAll('.pdf-thumbnail')).toHaveLength(25)
    expect(w.text()).not.toContain('下一组')
    await w.get('[aria-label="选择第13页"]').trigger('click')
    await w.get('[aria-label="选择第25页"]').trigger('click')
    expect(w.findAll('.pdf-thumbnail.checked')).toHaveLength(23)
    expect(w.get('[aria-label="选择第1页"]').attributes('aria-pressed')).toBe('true')
    expect(w.get('[aria-label="选择第25页"]').attributes('aria-pressed')).toBe('false')
  })
  it('edits multiple pages in the continuous document and preserves coordinates when zooming', async () => {
    const w = setup(); await w.findAll('.pdf-tabs button')[2]!.trigger('click'); await selectPdf(w)
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click'); await w.get('textarea').setValue('第一页')
    await w.get('[aria-label="前往第2页"]').trigger('click')
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click'); await w.get('textarea').setValue('第二页')
    const pages = w.findAll('.pdf-document-page')
    expect(pages).toHaveLength(2)
    expect(pages[0]!.get('.pdf-layer').text()).toBe('第一页')
    expect(pages[1]!.get('.pdf-layer').text()).toBe('第二页')
    const left = (pages[1]!.get('.pdf-layer').element as HTMLElement).style.left
    await w.get('[aria-label="放大页面"]').trigger('click')
    expect(w.get('[aria-label="缩放比例"]').text()).toBe('125%')
    expect((pages[1]!.get('.pdf-layer').element as HTMLElement).style.left).toBe(left)
    await w.get('[aria-label="编辑页码"]').setValue('999')
    expect((w.get('[aria-label="编辑页码"]').element as HTMLInputElement).value).toBe('2')
  })
  it('defaults image margins to two millimetres and rectangles to white fill with an outline option', async () => {
    const w = setup()
    await w.findAll('.pdf-tabs button')[1]!.trigger('click')
    expect((w.get('input[type=number]').element as HTMLInputElement).value).toBe('2')
    await w.findAll('.pdf-tabs button')[2]!.trigger('click'); await selectPdf(w)
    await w.findAll('.pdf-edit-actions button')[3]!.trigger('click')
    expect((w.get('input[type=color]').element as HTMLInputElement).value).toBe('#ffffff')
    expect((w.get('.pdf-layer.rectangle').element as HTMLElement).style.background).toBe('rgb(255, 255, 255)')
    await w.get('.layer-settings select').setValue('false')
    expect((w.get('.pdf-layer.rectangle').element as HTMLElement).style.background).toBe('')
  })

  it('resizes rectangles from corners without moving the opposite corner and clamps to the page', async () => {
    const w = setup(); await w.findAll('.pdf-tabs button')[2]!.trigger('click'); await selectPdf(w)
    await w.findAll('.pdf-edit-actions button')[3]!.trigger('click')
    vi.spyOn(w.get('.pdf-stage').element, 'getBoundingClientRect').mockReturnValue({ width: 600, height: 800 } as DOMRect)
    const pointer = (target: EventTarget, type: string, x: number, y: number) => {
      const e = new Event(type, { bubbles: true }); Object.assign(e, { button: 0, clientX: x, clientY: y }); target.dispatchEvent(e)
    }
    pointer(w.get('.pdf-resize-handle.se').element, 'pointerdown', 270, 152)
    pointer(window, 'pointermove', 330, 232); pointer(window, 'pointerup', 330, 232); await w.vm.$nextTick()
    const layer = w.get('.pdf-layer').element as HTMLElement
    expect(parseFloat(layer.style.left)).toBeCloseTo(10)
    expect(parseFloat(layer.style.width)).toBeCloseTo(45)
    expect(parseFloat(layer.style.height)).toBeCloseTo(19)
    pointer(w.get('.pdf-resize-handle.nw').element, 'pointerdown', 60, 80)
    pointer(window, 'pointermove', -600, -800); pointer(window, 'pointerup', -600, -800); await w.vm.$nextTick()
    expect(parseFloat(layer.style.left)).toBe(0)
    expect(parseFloat(layer.style.top)).toBe(0)
    expect(parseFloat(layer.style.width)).toBeCloseTo(55)
    pointer(window, 'pointermove', 400, 400); await w.vm.$nextTick()
    expect(parseFloat(layer.style.width)).toBeCloseTo(55)
  })

  it('summarizes overlapping ranges without silently removing separate output pages', async () => {
    const w = setup(); await selectPdf(w)
    await w.get('.pdf-settings select').setValue('ranges')
    await w.get('input[placeholder="例如：1-3,5,7-9"]').setValue('1-2,2')
    expect(w.get('#pdf-split-summary').text()).toContain('已选 2 页 · 生成 2 个文件')
    expect(w.get('#pdf-split-summary').text()).toContain('重复输出 1 页')
    await w.get('.pdf-settings select').setValue('merge')
    expect(w.get('#pdf-split-summary').text()).toContain('生成 1 个文件')
    expect(w.get('#pdf-split-summary').text()).toContain('已去重')
    await w.get('input[placeholder="例如：1-3,5,7-9"]').setValue('3')
    expect(w.find('[aria-invalid=true]').exists()).toBe(true)
    expect(w.get('#pdf-split-summary').text()).toContain('页码必须')
  })
  it('deletes a clicked text layer with the keyboard without intercepting text editing', async () => {
    const w = setup(); await w.findAll('.pdf-tabs button')[2]!.trigger('click'); await selectPdf(w)
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click')
    await w.get('textarea').setValue('保留文字')
    await w.get('textarea').trigger('keydown', { key: 'Backspace' })
    expect(w.findAll('.pdf-layer')).toHaveLength(1)
    const focus = vi.spyOn(w.get('.pdf-layer').element as HTMLElement, 'focus')
    w.get('.pdf-layer').element.dispatchEvent(new MouseEvent('pointerdown', { button: 0, clientX: 20, clientY: 20, bubbles: true })); await flushPromises()
    expect(focus).toHaveBeenCalledWith({ preventScroll: true })
    await w.get('.pdf-layer').trigger('keydown', { key: 'Backspace' })
    expect(w.findAll('.pdf-layer')).toHaveLength(0)
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click')
    await w.findAll('.pdf-edit-actions button').find(b => b.text() === '删除选中')!.trigger('click')
    expect(w.findAll('.pdf-layer')).toHaveLength(0)
  })
  it('defaults image paper to original pixels and previews every converted FBA page', async () => {
    const w = setup(); await w.findAll('.pdf-tabs button')[1]!.trigger('click')
    expect((w.get('.pdf-settings select').element as HTMLSelectElement).value).toBe('original')
    await w.findAll('.pdf-tabs button')[3]!.trigger('click'); await selectPdf(w, 'Labels.pdf', 14)
    await vi.waitFor(() => expect(w.get('.primary').attributes('disabled')).toBeUndefined())
    expect(w.findAll('.pdf-document-page')).toHaveLength(14)
    expect(w.text()).toContain('转换后 · 100 × 100 mm')
    expect(w.find('[aria-label="连续页面预览区"]').exists()).toBe(true)
    expect(w.findAll('.pdf-stage').every(p => (p.element as HTMLElement).style.aspectRatio.split('/').map(n => Number(n.trim())).every((n, _, a) => n === a[0]))).toBe(true)
  })
  it('copies a selected text layer to another page and edits the copy independently', async () => {
    const w = setup(); await w.findAll('.pdf-tabs button')[2]!.trigger('click'); await selectPdf(w)
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click')
    await w.get('textarea').setValue('第一页文字')
    await w.get('.layer-settings input[type=number]').setValue('24')
    await w.get('input[type=color]').setValue('#cc3322')
    expect((w.get('[aria-label="复制目标页"]').element as HTMLSelectElement).value).toBe('1')
    await w.get('.pdf-layer-copy-target button').trigger('click'); await flushPromises()
    const pages = w.findAll('.pdf-document-page')
    expect(w.get('[aria-label="编辑页码"]').element).toHaveProperty('value', '2')
    expect(pages[0]!.get('.pdf-layer').text()).toBe('第一页文字')
    expect(pages[1]!.get('.pdf-layer.selected').text()).toBe('第一页文字')
    expect((w.get('.layer-settings input[type=number]').element as HTMLInputElement).value).toBe('24')
    expect((w.get('input[type=color]').element as HTMLInputElement).value).toBe('#cc3322')
    expect((pages[1]!.get('.pdf-layer').element as HTMLElement).style.left).toBe((pages[0]!.get('.pdf-layer').element as HTMLElement).style.left)
    await w.get('textarea').setValue('第二页独立文字')
    expect(pages[0]!.get('.pdf-layer').text()).toBe('第一页文字')
    expect(pages[1]!.get('.pdf-layer').text()).toBe('第二页独立文字')
    await w.get('.layer-settings button').trigger('click')
    expect(pages[0]!.find('.pdf-layer').exists()).toBe(true)
    expect(pages[1]!.find('.pdf-layer').exists()).toBe(false)
  })
  it('does not offer another page as a copy target in a one-page PDF', async () => {
    const w = setup(); await w.findAll('.pdf-tabs button')[2]!.trigger('click'); await selectPdf(w, 'Single.pdf', 1)
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click')
    expect(w.find('.pdf-layer-copy-target').exists()).toBe(false)
    expect(w.find('.pdf-layer-controls').exists()).toBe(true)
  })
  it('copies and reorders only the current page layers and supports keyboard nudging', async () => {
    const w = setup(); await w.findAll('.pdf-tabs button')[2]!.trigger('click'); await selectPdf(w)
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click'); await w.get('textarea').setValue('第一层')
    await w.findAll('.pdf-edit-actions button')[0]!.trigger('click'); await w.get('textarea').setValue('第二层')
    await w.findAll('.pdf-layer-controls button')[0]!.trigger('click'); await flushPromises()
    expect(w.findAll('.pdf-layer')).toHaveLength(3)
    await w.get('textarea').setValue('复制层')
    await w.findAll('.pdf-layer-controls button')[2]!.trigger('click')
    expect(w.findAll('.pdf-layer-list button').map(b => b.text())).toEqual(['第二层', '复制层', '第一层'])
    const layer = w.get('.pdf-layer.selected')
    await layer.trigger('keydown', { key: 'ArrowRight' })
    expect(parseFloat((layer.element as HTMLElement).style.left)).toBeGreaterThan(10)
    await w.get('[aria-label="前往第2页"]').trigger('click')
    expect(w.find('.pdf-layer-panel').exists()).toBe(false)
    expect(w.find('.layer-settings').exists()).toBe(false)
  })

})
