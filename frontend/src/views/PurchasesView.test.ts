import { flushPromises, mount } from '@vue/test-utils'
import { createMemoryHistory, createRouter } from 'vue-router'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { costsApi } from '@/api/costs'
import { domainApi } from '@/api/domain'
import { purchaseApi, type PurchaseOrder, type PurchaseReferenceItem } from '@/api/purchases'
import { session } from '@/state/session'
import PurchasesView from './PurchasesView.vue'

vi.mock('@/api/costs',()=>({costsApi:{price:vi.fn()}}))
vi.mock('@/state/uiConfirmation', () => ({ confirmAction: vi.fn().mockResolvedValue(true) }))
vi.mock('@/api/domain', () => ({ domainApi: { suppliers: vi.fn(), materialSupplierLinks: vi.fn() } }))
vi.mock('@/api/purchases', () => ({ purchaseApi: { remove: vi.fn(), orders: vi.fn(), create: vi.fn(), update: vi.fn(), references: vi.fn() } }))
const order: PurchaseOrder = {
  id: 'order-1', orderNo: 'PO-MATERIAL', orderType: 'MATERIAL', supplierId: 'supplier-1', supplierName: '测试供应商', status: 'DRAFT', currency: 'CNY', version: 1,
  lines: [{ id: 'line-1', lineNo: 1, itemId: 'material-1', itemCode: 'MAT-001', itemName: '纸箱', unit: 'PCS', orderedQuantity: 10, receivedQuantity: 0, remainingQuantity: 10, unitPrice: 3 }],
  createdAt: '2026-10-16T08:00:00Z', updatedAt: '2026-10-16T08:00:00Z',
}
const item: PurchaseReferenceItem = { id: 'material-1', code: 'MAT-001', name: '纸箱', unit: 'PCS', primarySupplier: true }
const wrappers: ReturnType<typeof mount>[] = []
beforeEach(() => {
  vi.clearAllMocks()
  vi.mocked(costsApi.price).mockResolvedValue({netPrice:'0.5',unit:'PCS',source:'MANUAL',referenceId:null,reason:'测试',version:0})
  vi.mocked(domainApi.materialSupplierLinks).mockResolvedValue([{supplierId:'supplier-1',primary:true}] as never)
  vi.spyOn(session, 'canAccess').mockReturnValue(true)
  vi.mocked(purchaseApi.orders).mockResolvedValue([order, { ...order, id: 'order-2', orderNo: 'PO-PRODUCT', orderType: 'PRODUCT' }])
  vi.mocked(purchaseApi.references).mockResolvedValue([item])
  vi.mocked(purchaseApi.create).mockResolvedValue(order)
  vi.mocked(purchaseApi.update).mockResolvedValue(order)
  vi.mocked(domainApi.suppliers).mockResolvedValue({ items: [{ id: 'supplier-1', name: '供应商一' }, { id: 'supplier-2', name: '供应商二' }] as never, page: 0, size: 100, totalCount: 2 })
})
afterEach(() => { wrappers.splice(0).forEach(wrapper => wrapper.unmount()); vi.restoreAllMocks() })
async function setup(query = '') {
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/purchases/orders', component: PurchasesView }] })
  await router.push(`/purchases/orders${query}`); await router.isReady()
  const wrapper = mount(PurchasesView, { global: { plugins: [router] } }); wrappers.push(wrapper); await flushPromises()
  return { wrapper, router }
}
describe('purchase order workspace', () => {
  it('opens a material purchase with its primary supplier and requested item, without creating automatically', async () => {
    const {wrapper,router}=await setup('?type=MATERIAL&materialId=material-1')
    expect(domainApi.materialSupplierLinks).toHaveBeenCalledWith('material-1')
    expect(wrapper.get('fieldset select').element).toHaveProperty('value','supplier-1')
    expect(wrapper.get('[aria-label="采购项目 1"]').element).toHaveProperty('value','material-1')
    expect(wrapper.get('[aria-label="采购单价"]').element).toHaveProperty('value','0.5')
    expect(purchaseApi.create).not.toHaveBeenCalled()
    expect(router.currentRoute.value.query.materialId).toBeUndefined()
    await wrapper.get('[aria-label="采购数量"]').setValue(4)
    await wrapper.get('[aria-label="采购单价"]').setValue(2.5)
    await wrapper.get('form').trigger('submit');await flushPromises()
    expect(purchaseApi.create).toHaveBeenCalledWith(expect.objectContaining({orderType:'MATERIAL',supplierId:'supplier-1',lines:[expect.objectContaining({itemId:'material-1',quantity:4,unitPrice:2.5})]}))
  })
  it('does not use a cost with a different unit and explains price load failure', async () => {
    vi.mocked(costsApi.price).mockResolvedValueOnce({netPrice:'0.5',unit:'KG'} as never)
    const {wrapper}=await setup('?type=MATERIAL&materialId=material-1')
    expect(wrapper.text()).toContain('单位或币制与采购单不一致')
    expect(wrapper.get('[aria-label="采购单价"]').element).toHaveProperty('value','0')
    vi.mocked(costsApi.price).mockRejectedValueOnce(new Error('offline'))
    await wrapper.get('fieldset select').setValue('supplier-2');await flushPromises()
    expect(wrapper.text()).toContain('成本价读取失败')
  })
  it('explains missing supplier links and does not silently select an unrelated material', async () => {
    vi.mocked(domainApi.materialSupplierLinks).mockResolvedValue([])
    const {wrapper}=await setup('?type=MATERIAL&materialId=missing')
    expect(wrapper.text()).toContain('当前辅料未关联启用的供应商')
    expect(purchaseApi.create).not.toHaveBeenCalled()
    await wrapper.get('fieldset select').setValue('supplier-2');await flushPromises()
    expect(wrapper.text()).toContain('该供应商未关联当前辅料')
    expect(wrapper.get('[aria-label="采购项目 1"]').element).toHaveProperty('value','')
  })
  it('prefills every selected material and its cost for a common supplier', async () => {
    vi.mocked(purchaseApi.references).mockResolvedValue([item,{...item,id:'material-2',name:'胶带'}])
    const {wrapper}=await setup('?type=MATERIAL&materialIds=material-1,material-2')
    expect(domainApi.materialSupplierLinks).toHaveBeenCalledWith('material-2')
    expect(wrapper.get('[aria-label="采购项目 1"]').element).toHaveProperty('value','material-1')
    expect(wrapper.get('[aria-label="采购项目 2"]').element).toHaveProperty('value','material-2')
    expect(wrapper.findAll('[aria-label="采购单价"]').map(x=>(x.element as HTMLInputElement).value)).toEqual(['0.5','0.5'])
    await wrapper.get('form').trigger('submit');await flushPromises()
    expect(purchaseApi.create).toHaveBeenCalledWith(expect.objectContaining({lines:[expect.objectContaining({itemId:'material-1',unitPrice:0.5}),expect.objectContaining({itemId:'material-2',unitPrice:0.5})]}))
  })
  it('does not silently drop materials without a common supplier', async () => {
    vi.mocked(domainApi.materialSupplierLinks).mockResolvedValueOnce([{supplierId:'supplier-1',primary:true}] as never).mockResolvedValueOnce([{supplierId:'supplier-2',primary:true}] as never)
    const {wrapper}=await setup('?type=MATERIAL&materialIds=material-1,material-2')
    expect(wrapper.text()).toContain('没有共同的启用供应商')
    await wrapper.get('fieldset select').setValue('supplier-1');await flushPromises()
    expect(wrapper.text()).toContain('部分所选辅料')
    await wrapper.get('form').trigger('submit');await flushPromises()
    expect(purchaseApi.create).not.toHaveBeenCalled()
  })
  it('groups each purchase item image, name and code together like customer orders', async () => {
    vi.mocked(purchaseApi.orders).mockResolvedValue([{...order,lines:[order.lines[0]!,{...order.lines[0]!,id:'line-2',itemName:'胶带',itemCode:'MAT-002'}]}])
    const {wrapper}=await setup('?type=MATERIAL')
    const products=wrapper.findAll('.purchase-list-product')
    expect(products).toHaveLength(2)
    expect(products[0]!.text()).toContain('纸箱')
    expect(products[0]!.text()).toContain('MAT-001')
    expect(products[1]!.text()).toContain('胶带')
    expect(products[1]!.text()).toContain('MAT-002')
    expect(wrapper.get('thead').text()).not.toContain('商品图片')
    expect(wrapper.text()).toContain('共 2 项')
  })
  it('defaults to CNY and two days ahead and synchronizes cost when selecting an item', async () => {
    const {wrapper}=await setup('?type=MATERIAL')
    await wrapper.get('.purchase-header button').trigger('click');await flushPromises()
    expect(wrapper.get('form').text()).not.toContain('币种')
    await wrapper.get('fieldset select').setValue('supplier-1');await flushPromises()
    await wrapper.get('[aria-label="采购项目 1"]').setValue('material-1');await flushPromises()
    expect(wrapper.get('[aria-label="采购单价"]').element).toHaveProperty('value','0.5')
    await wrapper.get('form').trigger('submit');await flushPromises()
    const day=new Intl.DateTimeFormat('sv-SE',{timeZone:'Asia/Shanghai'}).format(new Date())
    const date=new Date(day+'T00:00:00Z');date.setUTCDate(date.getUTCDate()+2)
    expect(purchaseApi.create).toHaveBeenCalledWith(expect.objectContaining({currency:'CNY',expectedDeliveryDate:date.toISOString().slice(0,10)}))
  })
  it('separates product and material orders and persists tab in the URL', async () => {
    const { wrapper, router } = await setup()
    expect(wrapper.text()).toContain('PO-PRODUCT'); expect(wrapper.text()).not.toContain('PO-MATERIAL')
    await wrapper.get('#tab-MATERIAL').trigger('click'); await flushPromises()
    expect(router.currentRoute.value.query.type).toBe('MATERIAL')
    expect(wrapper.text()).toContain('PO-MATERIAL'); expect(wrapper.text()).not.toContain('PO-PRODUCT')
  })
  it('filters by item or supplier and keeps write actions hidden for read-only users', async () => {
    vi.mocked(session.canAccess).mockReturnValue(false)
    const { wrapper } = await setup('?type=MATERIAL')
    expect(wrapper.findAll('button').map(button => button.text())).not.toContain('编辑')
    expect(wrapper.text()).not.toContain('新建辅料采购单')
    await wrapper.get('[aria-label="搜索采购单"]').setValue('no-match')
    expect(wrapper.text()).not.toContain('PO-MATERIAL')
    await wrapper.get('[aria-label="搜索采购单"]').setValue('纸箱')
    expect(wrapper.text()).toContain('PO-MATERIAL')
  })
  it('creates the current tab type with delivery details and never mixes item types', async () => {
    const { wrapper } = await setup('?type=MATERIAL')
    await wrapper.get('.purchase-header button').trigger('click'); await flushPromises()
    await wrapper.get('fieldset select').setValue('supplier-1'); await flushPromises()
    expect(purchaseApi.references).toHaveBeenCalledWith('MATERIAL', 'supplier-1')
    await wrapper.get('[aria-label="采购项目 1"]').setValue('material-1')
    await wrapper.get('[aria-label="采购数量"]').setValue(4)
    await wrapper.get('[aria-label="采购单价"]').setValue(2.5)
    await wrapper.get('input[type="date"]').setValue('2026-11-01')
    await wrapper.get('input[placeholder="收货地址、联系人或内部仓库说明"]').setValue('测试固定仓')
    expect(wrapper.text()).toContain('合计 CNY 10.00')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(purchaseApi.create).toHaveBeenCalledWith(expect.objectContaining({ orderType: 'MATERIAL', expectedDeliveryDate: '2026-11-01', deliveryAddress: '测试固定仓', lines: [{ itemId: 'material-1', quantity: 4, unitPrice: 2.5 }] }))
  })
  it('ignores a stale supplier response and refuses invalid quantities', async () => {
    let resolveFirst!: (items: PurchaseReferenceItem[]) => void
    vi.mocked(purchaseApi.references).mockImplementationOnce(() => new Promise(resolve => { resolveFirst = resolve }))
      .mockResolvedValueOnce([{ ...item, id: 'other', code: 'OTHER' }])
    const { wrapper } = await setup('?type=MATERIAL')
    await wrapper.get('.purchase-header button').trigger('click'); await flushPromises()
    await wrapper.get('fieldset select').setValue('supplier-1')
    await wrapper.get('fieldset select').setValue('supplier-2'); await flushPromises()
    resolveFirst([item]); await flushPromises()
    expect(wrapper.get('[aria-label="采购项目 1"]').text()).toContain('纸箱')
    expect(wrapper.get('[aria-label="采购项目 1"]').find('option[value="material-1"]').exists()).toBe(false)
    await wrapper.get('[aria-label="采购项目 1"]').setValue('other')
    await wrapper.get('[aria-label="采购数量"]').setValue(0)
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(purchaseApi.create).not.toHaveBeenCalled(); expect(wrapper.text()).toContain('数量必须大于 0')
  })
  it('resets pagination when filters or tab change', async () => {
    vi.mocked(purchaseApi.orders).mockResolvedValue(Array.from({ length: 25 }, (_, i) => ({ ...order, id: `order-${i}`, orderNo: `PO-${i}` })))
    const { wrapper } = await setup('?type=MATERIAL')
    await wrapper.get('[aria-label="下一页"]').trigger('click')
    expect(wrapper.get('.purchase-pagination').text()).toContain('2 / 2')
    await wrapper.get('[aria-label="搜索采购单"]').setValue('PO-24')
    expect(wrapper.get('.purchase-pagination').text()).toContain('1 / 1')
    expect(wrapper.text()).toContain('PO-24')
  })
})

it('deletes an unreceived purchase with its version and removes it from the list', async () => {
  const { wrapper } = await setup('?type=MATERIAL')
  vi.mocked(purchaseApi.remove).mockResolvedValue(undefined)
  await wrapper.findAll('button').find(b => b.text() === '删除')!.trigger('click'); await flushPromises()
  expect(purchaseApi.remove).toHaveBeenCalledWith('order-1', 1)
  expect(wrapper.text()).not.toContain('PO-MATERIAL')
})
it('disables deleting received orders and keeps failed deletions visible', async () => {
  vi.mocked(purchaseApi.orders).mockResolvedValue([{ ...order, status: 'CANCELLED', lines: [{ ...order.lines[0]!, receivedQuantity: 2 }] }])
  const { wrapper } = await setup('?type=MATERIAL')
  expect(wrapper.findAll('button').find(b => b.text() === '删除')!.attributes('disabled')).toBeDefined()
  expect(purchaseApi.remove).not.toHaveBeenCalled()
})
it('does not remove a row after server rejection', async () => {
  const { wrapper } = await setup('?type=MATERIAL')
  vi.mocked(purchaseApi.remove).mockRejectedValue(new Error('offline'))
  await wrapper.findAll('button').find(b => b.text() === '删除')!.trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('PO-MATERIAL'); expect(wrapper.text()).toContain('删除结果未确认')
})

